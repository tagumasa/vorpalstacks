// PublicKey represents a CloudTrail public key used for log file validation.
type PublicKey struct {
	PublicKeyID       string    `json:"publicKeyId"`
	Value             []byte    `json:"value"`
	ValidityStartTime time.Time `json:"validityStartTime"`
	ValidityEndTime   time.Time `json:"validityEndTime"`
	TrailName         string    `json:"trailName,omitempty"`
	// PrivateKeyDER carries the PKCS#1 DER private half for trail
	// validation keys so the hourly digest chain can keep signing across
	// restarts. Per-delivery query signing keys leave it empty.
	PrivateKeyDER []byte `json:"privateKeyDer,omitempty"`
}

// GenerateKeyPair generates an RSA key pair using the common crypto utility.
// The returned public half is DER encoded in PKCS#1 form — the PublicKey
// contract documents Value as "The DER encoded public key value in PKCS#1
// format" — and is suitable for CloudTrail log file validation; the private
// half is the signer for digest and query result sign files and is never
// persisted.
func GenerateKeyPair() (*PublicKey, *rsa.PrivateKey, error) {
	privKey, err := vcrypto.GenerateRSAKey(vcrypto.DefaultRSAKeySize)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to generate RSA key pair: %w", err)
	}

	derBytes := x509.MarshalPKCS1PublicKey(&privKey.PublicKey)

	now := time.Now().UTC()
	return &PublicKey{
		PublicKeyID:       "K" + uuid.NewString(),
		Value:             derBytes,
		ValidityStartTime: now,
		ValidityEndTime:   now.Add(PublicKeyValidity),
	}, privKey, nil
}

// Fingerprint derives the key's fingerprint from the exact bytes Value
// serves: the lowercase hexadecimal encoding of the MD5 digest of the DER
// value. The digest file reference documents the fingerprint as
// "hexadecimal encoded" and its sample value is 32 hex characters (16
// bytes), which fixes the length; the digest algorithm itself is not
// documented, and hashing the served bytes lets a validator recompute the
// fingerprint from Value. The identifier is matched by equality only —
// the signatures carry the integrity protection (SHA256withRSA).
func (pk *PublicKey) Fingerprint() string {
	return hex.EncodeToString(vcrypto.MD5Hash(pk.Value))
}

