// QueryTerminalStatus reports whether a query status admits no further
// transitions. TIMED_OUT and CANCELLED are terminal exactly like FINISHED
// and FAILED; QUEUED and RUNNING are the live states.
func QueryTerminalStatus(status string) bool {
	return status == "FINISHED" || status == "FAILED" ||
		status == "CANCELLED" || status == "TIMED_OUT"
}

