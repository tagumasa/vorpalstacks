// NewEvent creates a new CloudTrail event. The readOnly flag carries the
// operation's read-only classification in the wire string form the
// LookupEvents response and the record JSON use.
func NewEvent(eventName, eventSource string, userIdentity *UserIdentity, readOnly bool) *Event {
	now := time.Now().UTC()
	readOnlyStr := "false"
	if readOnly {
		readOnlyStr = "true"
	}
	return &Event{
		EventID:       generateEventID(),
		EventName:     eventName,
		EventSource:   eventSource,
		EventTime:     now,
		EventType:     "AwsApiCall",
		EventVersion:  "1.08",
		EventCategory: "Management",
		UserIdentity:  userIdentity,
		Resources:     []Resource{},
		ReadOnly:      readOnlyStr,
	}
}

func generateEventID() string {
	return uuid.NewString()
}

// generateCloudTrailEvent populates the CloudTrailEvent field with the
// event's JSON in the AWS CloudTrail record format (the CloudTrail record
// contents reference): eventID and requestID spellings, boolean readOnly,
// awsRegion, record-shaped resources entries, and the identity's
// sessionContext when temporary credentials made the call.
func (e *Event) generateCloudTrailEvent() {
	if e.CloudTrailEvent != "" {
		return
	}

	record := &cloudTrailRecord{
		EventVersion:      e.EventVersion,
		UserIdentity:      e.UserIdentity,
		EventTime:         e.EventTime.UTC().Truncate(time.Second).Format(time.RFC3339),
		EventSource:       e.EventSource,
		EventName:         e.EventName,
		AWSRegion:         e.AwsRegion,
		SourceIPAddress:   e.SourceIPAddress,
		UserAgent:         e.UserAgent,
		ErrorCode:         e.ErrorCode,
		ErrorMessage:      e.ErrorMessage,
		RequestParameters: e.RequestParameters,
		ResponseElements:  e.ResponseElements,
		RequestID:         e.RequestID,
		EventID:           e.EventID,
		ReadOnly:          e.ReadOnly == "true",
		EventType:         e.EventType,
		ManagementEvent:   true,
		EventCategory:     e.EventCategory,
	}
	for _, r := range e.Resources {
		entry := recordResource{ARN: r.ResourceName, Type: r.ResourceType}
		if parsed, err := svcarn.ParseARN(r.ResourceName); err == nil {
			entry.AccountID = parsed.AccountID
		}
		record.Resources = append(record.Resources, entry)
	}

	b, err := json.Marshal(record)
	if err != nil {
		return
	}
	e.CloudTrailEvent = string(b)
}

// cloudTrailRecord mirrors the AWS CloudTrail record format so the stored
// CloudTrailEvent JSON parses as a CloudTrail record: the keys carry the
// record spellings (eventID, requestID), readOnly is a JSON boolean,
// requestParameters and responseElements are always present (null when the
// operation has none, as AWS emits for read-only APIs), and resources
// entries carry ARN, accountId and the AWS::service::type identifier.
type cloudTrailRecord struct {
	EventVersion      string                 `json:"eventVersion"`
	UserIdentity      *UserIdentity          `json:"userIdentity"`
	EventTime         string                 `json:"eventTime"`
	EventSource       string                 `json:"eventSource"`
	EventName         string                 `json:"eventName"`
	AWSRegion         string                 `json:"awsRegion"`
	SourceIPAddress   string                 `json:"sourceIpAddress,omitempty"`
	UserAgent         string                 `json:"userAgent,omitempty"`
	ErrorCode         string                 `json:"errorCode,omitempty"`
	ErrorMessage      string                 `json:"errorMessage,omitempty"`
	RequestParameters map[string]interface{} `json:"requestParameters"`
	ResponseElements  map[string]interface{} `json:"responseElements"`
	RequestID         string                 `json:"requestID,omitempty"`
	EventID           string                 `json:"eventID"`
	ReadOnly          bool                   `json:"readOnly"`
	Resources         []recordResource       `json:"resources,omitempty"`
	EventType         string                 `json:"eventType"`
	ManagementEvent   bool                   `json:"managementEvent"`
	EventCategory     string                 `json:"eventCategory"`
}

// recordResource is a record-format resources entry. The ARN key is
// capitalised per the AWS record example; the type identifier
// (AWS::{{service}}::{{type}}) and the resource owner's accountId are
// optional record fields.
type recordResource struct {
	ARN       string `json:"ARN"`
	AccountID string `json:"accountId,omitempty"`
	Type      string `json:"type,omitempty"`
}
