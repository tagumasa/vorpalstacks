const testAccountID = "123456789012"

func resourcePolicyDoc(statements ...string) string {
	return `{"Version":"2012-10-17","Statement":[` + strings.Join(statements, ",") + `]}`
}

// TestParseResourcePolicyDocument pins the document parser: verbatim
// statement JSON is preserved, the authorisation fields are derived for
// Allow statements with string-shaped members, Deny statements and
// non-string members leave them empty, and malformed documents are
// rejected as InvalidParameterValueException.
func TestParseResourcePolicyDocument(t *testing.T) {
	t.Run("allow statement with object principal", func(t *testing.T) {
		doc := resourcePolicyDoc(`{"Sid":"s1","Effect":"Allow","Principal":{"AWS":"arn:aws:iam::` + testAccountID + `:root"},"Action":"lambda:InvokeFunction","Resource":"arn:aws:lambda:us-east-1:` + testAccountID + `:function:fn"}`)
		entries, err := parseResourcePolicyDocument(doc)
		if err != nil {
			t.Fatalf("parse: %v", err)
		}
		if len(entries) != 1 {
			t.Fatalf("got %d entries, want 1", len(entries))
		}
		e := entries[0]
		if e.Id != "s1" {
			t.Fatalf("Id %q, want s1", e.Id)
		}
		if e.Principal != "arn:aws:iam::"+testAccountID+":root" {
			t.Fatalf("Principal %q", e.Principal)
		}
		if e.Effect != "Allow" {
			t.Fatalf("Effect %q, want Allow", e.Effect)
		}
		if e.Action != "lambda:InvokeFunction" || e.Resource != "arn:aws:lambda:us-east-1:"+testAccountID+":function:fn" {
			t.Fatalf("Action/Resource %q/%q", e.Action, e.Resource)
		}
		if !strings.Contains(e.Raw, `"Sid":"s1"`) || !strings.Contains(e.Raw, `"Effect":"Allow"`) {
			t.Fatalf("Raw does not reproduce the statement: %q", e.Raw)
		}
	})

	t.Run("service principal object", func(t *testing.T) {
		doc := resourcePolicyDoc(`{"Sid":"s2","Effect":"Allow","Principal":{"Service":"s3.amazonaws.com"},"Action":"lambda:InvokeFunction","Resource":"arn:aws:lambda:us-east-1:` + testAccountID + `:function:fn"}`)
		entries, err := parseResourcePolicyDocument(doc)
		if err != nil {
			t.Fatalf("parse: %v", err)
		}
		if entries[0].Principal != "s3.amazonaws.com" {
			t.Fatalf("Principal %q, want s3.amazonaws.com", entries[0].Principal)
		}
	})

	t.Run("deny statement grants nothing", func(t *testing.T) {
		doc := resourcePolicyDoc(`{"Sid":"d1","Effect":"Deny","Principal":"*","Action":"lambda:InvokeFunction","Resource":"arn"}`)
		entries, err := parseResourcePolicyDocument(doc)
		if err != nil {
			t.Fatalf("parse: %v", err)
		}
		e := entries[0]
		if e.Effect != "Deny" {
			t.Fatalf("Effect %q, want Deny", e.Effect)
		}
		if e.Principal != "" || e.Action != "" || e.Resource != "" {
			t.Fatalf("Deny statement populated the authorisation fields: %+v", e)
		}
		if !strings.Contains(e.Raw, `"Effect":"Deny"`) {
			t.Fatalf("Raw lost the Deny effect: %q", e.Raw)
		}
	})

	t.Run("array action leaves the field empty", func(t *testing.T) {
		doc := resourcePolicyDoc(`{"Sid":"a1","Effect":"Allow","Principal":"*","Action":["lambda:InvokeFunction","lambda:GetFunction"],"Resource":"arn"}`)
		entries, err := parseResourcePolicyDocument(doc)
		if err != nil {
			t.Fatalf("parse: %v", err)
		}
		if entries[0].Action != "" || entries[0].Principal != "*" {
			t.Fatalf("array Action populated fields: %+v", entries[0])
		}
	})

	t.Run("single statement object form", func(t *testing.T) {
		doc := `{"Version":"2012-10-17","Statement":{"Sid":"single","Effect":"Allow","Principal":"*","Action":"lambda:InvokeFunction","Resource":"arn"}}`
		entries, err := parseResourcePolicyDocument(doc)
		if err != nil {
			t.Fatalf("parse: %v", err)
		}
		if len(entries) != 1 || entries[0].Id != "single" {
			t.Fatalf("entries %v, want one with Id single", entries)
		}
	})

	t.Run("statement without Sid parses", func(t *testing.T) {
		doc := resourcePolicyDoc(`{"Effect":"Allow","Principal":"*","Action":"lambda:InvokeFunction","Resource":"arn"}`)
		entries, err := parseResourcePolicyDocument(doc)
		if err != nil {
			t.Fatalf("parse: %v", err)
		}
		if entries[0].Id != "" {
			t.Fatalf("Id %q, want empty (generated by the store)", entries[0].Id)
		}
	})

	t.Run("rejections", func(t *testing.T) {
		for name, doc := range map[string]string{
			"not json":              `not json`,
			"not an object":         `["statement"]`,
			"missing statement":     `{"Version":"2012-10-17"}`,
			"empty statement array": resourcePolicyDoc(),
			"scalar statement":      `{"Statement":"allow"}`,
			"scalar in array":       resourcePolicyDoc(`"allow"`),
			"non-string sid":        resourcePolicyDoc(`{"Sid":7,"Effect":"Allow"}`),
			"unknown effect":        resourcePolicyDoc(`{"Sid":"s","Effect":"Permit","Principal":"*","Action":"lambda:InvokeFunction","Resource":"arn"}`),
			"missing effect":        resourcePolicyDoc(`{"Sid":"s","Principal":"*","Action":"lambda:InvokeFunction","Resource":"arn"}`),
			"non-string effect":     resourcePolicyDoc(`{"Sid":"s","Effect":["Allow"],"Principal":"*","Action":"lambda:InvokeFunction","Resource":"arn"}`),
			"missing principal":     resourcePolicyDoc(`{"Sid":"s","Effect":"Allow","Action":"lambda:InvokeFunction","Resource":"arn"}`),
			"missing action":        resourcePolicyDoc(`{"Sid":"s","Effect":"Allow","Principal":"*"}`),
		} {
			if _, err := parseResourcePolicyDocument(doc); err == nil {
				t.Fatalf("%s: parse accepted an invalid document", name)
			} else if lambdaErr, ok := err.(*LambdaError); !ok || lambdaErr.Code != "InvalidParameterValueException" {
				t.Fatalf("%s: error = %v, want InvalidParameterValueException", name, err)
			}
		}
	})
}

// TestValidateResourcePolicyArn pins the PolicyResourceArn bound: a
// complete function ARN with optional qualifier parses into name and
// qualifier, and anything else is rejected.
func TestValidateResourcePolicyArn(t *testing.T) {
	valid := map[string][2]string{
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:fn":                   {"fn", ""},
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:fn:PROD":              {"fn", "PROD"},
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:fn:1":                 {"fn", "1"},
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:fn:$LATEST":           {"fn", "$LATEST"},
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:fn:$LATEST.PUBLISHED": {"fn", "$LATEST.PUBLISHED"},
		"arn:aws-us-gov:lambda:us-gov-west-1:" + testAccountID + ":function:fn":        {"fn", ""},
		"arn:aws:lambda:eusc-us-east-1:" + testAccountID + ":function:fn":              {"fn", ""},
		"arn:aws:lambda:us-iso-east-1:" + testAccountID + ":function:fn":               {"fn", ""},
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:fn_with-dashes_1":     {"fn_with-dashes_1", ""},
	}
	for arn, want := range valid {
		name, qualifier, err := validateResourcePolicyArn(arn)
		if err != nil {
			t.Fatalf("arn %s: %v", arn, err)
		}
		if name != want[0] || qualifier != want[1] {
			t.Fatalf("arn %s parsed to (%q, %q), want (%q, %q)", arn, name, qualifier, want[0], want[1])
		}
	}

	for _, arn := range []string{
		"",
		"fn",
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:*",
		"arn:aws:sqs:us-east-1:" + testAccountID + ":queue",
		"arn:aws:lambda:us-east-1:" + testAccountID + ":layer:lay:1",
		"arn:aws:lambda:NOT_A_REGION:" + testAccountID + ":function:fn",
		"arn:aws:lambda:us-east-1:12345:function:fn",
		"arn:aws:lambda:us-east-1:" + testAccountID + ":function:",
	} {
		if _, _, err := validateResourcePolicyArn(arn); err == nil {
			t.Fatalf("arn %q accepted", arn)
		}
	}
}

// TestRenderResourcePolicyDocument pins the shared renderer: verbatim
// statements are embedded unchanged and AddPermission statements render
// through buildPermissionStatement.
func TestRenderResourcePolicyDocument(t *testing.T) {
	rawStatement := `{"Sid":"raw","Effect":"Allow","Principal":{"Service":"s3.amazonaws.com"},"Action":"lambda:InvokeFunction","Resource":"` + coreTestFunctionArn() + `"}`
	rendered, err := renderResourcePolicyDocument([]lambdastore.FunctionPolicy{
		{Id: "raw", Raw: rawStatement},
		{Id: "added", Principal: "apigateway.amazonaws.com", Action: "lambda:InvokeFunction", Resource: "arn"},
	})
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	var doc struct {
		Version   string                   `json:"Version"`
		Statement []map[string]interface{} `json:"Statement"`
	}
	if err := json.Unmarshal([]byte(rendered), &doc); err != nil {
		t.Fatalf("rendered document is not valid JSON: %v", err)
	}
	if doc.Version != "2012-10-17" {
		t.Fatalf("Version %q", doc.Version)
	}
	if len(doc.Statement) != 2 {
		t.Fatalf("statements %d, want 2", len(doc.Statement))
	}
	rawPrincipal, _ := doc.Statement[0]["Principal"].(map[string]interface{})
	if rawPrincipal["Service"] != "s3.amazonaws.com" {
		t.Fatalf("verbatim statement principal altered: %v", doc.Statement[0]["Principal"])
	}
	if doc.Statement[1]["Sid"] != "added" || doc.Statement[1]["Effect"] != "Allow" {
		t.Fatalf("AddPermission statement rendered wrong: %v", doc.Statement[1])
	}
	builtPrincipal, _ := doc.Statement[1]["Principal"].(map[string]interface{})
	if builtPrincipal["Service"] != "apigateway.amazonaws.com" {
		t.Fatalf("AddPermission principal not wrapped: %v", doc.Statement[1]["Principal"])
	}
}

// resourcePolicyCoreFixture seeds a function store for the core tests.
