func coreTestFunctionArn() string {
	return "arn:aws:lambda:us-east-1:" + testAccountID + ":function:fn"
}

// TestResourcePolicyCoreRoundTrip pins the operation cores together: a
// Put installs the document under a fresh revision and replaces prior
// AddPermission statements, Get renders it back with the revision, the
// revision precondition rejects stale writers, and Delete removes the
// policy so Get answers ResourceNotFound.
func TestResourcePolicyCoreRoundTrip(t *testing.T) {
	svc := &LambdaService{}
	store := resourcePolicyCoreFixture(t)
	arn := coreTestFunctionArn()

	// An AddPermission statement is replaced by the first Put.
	if _, _, err := svc.addPermissionCore(store, &lambdastore.Function{FunctionName: "fn", FunctionArn: arn}, &AddPermissionInput{
		StatementId: "legacy",
		Principal:   "apigateway.amazonaws.com",
		Action:      "lambda:InvokeFunction",
	}); err != nil {
		t.Fatalf("add permission: %v", err)
	}

	doc := resourcePolicyDoc(`{"Sid":"rbp","Effect":"Allow","Principal":{"AWS":"arn:aws:iam::` + testAccountID + `:root"},"Action":"lambda:InvokeFunction","Resource":"` + arn + `"}`)
	put, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{ResourceArn: arn, Policy: doc})
	if err != nil {
		t.Fatalf("put: %v", err)
	}
	if put.RevisionId == "" {
		t.Fatal("put returned no revision")
	}
	var putDoc map[string]interface{}
	if err := json.Unmarshal([]byte(put.Policy), &putDoc); err != nil {
		t.Fatalf("put response policy is not valid JSON: %v", err)
	}

	got, err := svc.getResourcePolicyCore(store, arn)
	if err != nil {
		t.Fatalf("get: %v", err)
	}
	if got.RevisionId != put.RevisionId {
		t.Fatalf("get revision %q, want the put revision %q", got.RevisionId, put.RevisionId)
	}
	var gotDoc struct {
		Statement []map[string]interface{} `json:"Statement"`
	}
	if err := json.Unmarshal([]byte(got.Policy), &gotDoc); err != nil {
		t.Fatalf("get response policy is not valid JSON: %v", err)
	}
	if len(gotDoc.Statement) != 1 || gotDoc.Statement[0]["Sid"] != "rbp" {
		t.Fatalf("get statements %v, want only rbp", gotDoc.Statement)
	}

	// A stale revision cannot replace or delete the policy.
	if _, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{
		ResourceArn: arn, Policy: doc, RevisionId: "00000000-0000-0000-0000-000000000000",
	}); err == nil || err.(*LambdaError).Code != "PreconditionFailedException" {
		t.Fatalf("stale-revision put error = %v, want PreconditionFailedException", err)
	}
	if err := svc.deleteResourcePolicyCore(store, &DeleteResourcePolicyInput{
		ResourceArn: arn, RevisionId: "00000000-0000-0000-0000-000000000000",
	}); err == nil || err.(*LambdaError).Code != "PreconditionFailedException" {
		t.Fatalf("stale-revision delete error = %v, want PreconditionFailedException", err)
	}

	// The current revision deletes the policy.
	if err := svc.deleteResourcePolicyCore(store, &DeleteResourcePolicyInput{ResourceArn: arn, RevisionId: put.RevisionId}); err != nil {
		t.Fatalf("delete: %v", err)
	}
	if _, err := svc.getResourcePolicyCore(store, arn); err == nil || err.(*LambdaError).Code != "ResourceNotFoundException" {
		t.Fatalf("get after delete error = %v, want ResourceNotFoundException", err)
	}
	if err := svc.deleteResourcePolicyCore(store, &DeleteResourcePolicyInput{ResourceArn: arn}); err != nil {
		t.Fatalf("second delete: %v", err)
	}
}

// TestResourcePolicyCoreValidation pins the rejection paths: malformed
// documents, the policy length quota, malformed resource ARNs, unknown
// functions, and unresolvable qualifiers.
func TestResourcePolicyCoreValidation(t *testing.T) {
	svc := &LambdaService{}
	store := resourcePolicyCoreFixture(t)
	arn := coreTestFunctionArn()
	missingArn := "arn:aws:lambda:us-east-1:" + testAccountID + ":function:missing"

	cases := []struct {
		name string
		err  error
		code string
	}{
		{name: "empty policy", err: func() error {
			_, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{ResourceArn: arn})
			return err
		}(), code: "InvalidParameterValueException"},
		{name: "oversized policy", err: func() error {
			_, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{
				ResourceArn: arn,
				Policy:      resourcePolicyDoc(`{"Sid":"big","Effect":"Allow","Principal":"*","Action":"lambda:InvokeFunction","Resource":"` + strings.Repeat("a", lambdastore.MaxResourcePolicyLength) + `"}`),
			})
			return err
		}(), code: "PolicyLengthExceededException"},
		{name: "malformed document", err: func() error {
			_, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{ResourceArn: arn, Policy: `{"no":"statements"}`})
			return err
		}(), code: "InvalidParameterValueException"},
		{name: "malformed arn", err: func() error {
			_, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{ResourceArn: "fn", Policy: `{"Statement":[]}`})
			return err
		}(), code: "InvalidParameterValueException"},
		{name: "unknown function put", err: func() error {
			_, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{
				ResourceArn: missingArn,
				Policy:      resourcePolicyDoc(`{"Sid":"s","Effect":"Allow","Principal":"*","Action":"lambda:InvokeFunction","Resource":"` + missingArn + `"}`),
			})
			return err
		}(), code: "ResourceNotFoundException"},
		{name: "unknown function get", err: func() error {
			_, err := svc.getResourcePolicyCore(store, missingArn)
			return err
		}(), code: "ResourceNotFoundException"},
		{name: "unknown function delete", err: func() error {
			return svc.deleteResourcePolicyCore(store, &DeleteResourcePolicyInput{ResourceArn: missingArn})
		}(), code: "ResourceNotFoundException"},
		{name: "unresolvable qualifier", err: func() error {
			_, err := svc.getResourcePolicyCore(store, arn+":nosuchalias")
			return err
		}(), code: "ResourceNotFoundException"},
	}
	for _, tc := range cases {
		if tc.err == nil {
			t.Fatalf("%s: accepted", tc.name)
		}
		lambdaErr, ok := tc.err.(*LambdaError)
		if !ok {
			t.Fatalf("%s: error type %T, want *LambdaError", tc.name, tc.err)
		}
		if lambdaErr.Code != tc.code {
			t.Fatalf("%s: error code %q, want %q", tc.name, lambdaErr.Code, tc.code)
		}
	}
}

// TestResourcePolicyCoreQualifiedArn pins that a qualified ResourceArn
// resolves through the qualifier machinery the way AddPermission does,
// and stores the policy on the function itself.
func TestResourcePolicyCoreQualifiedArn(t *testing.T) {
	svc := &LambdaService{}
	store := resourcePolicyCoreFixture(t)

	if _, err := store.Functions.PublishVersionAtomically("fn", "", ""); err != nil {
		t.Fatalf("publish version: %v", err)
	}
	qualifiedArn := coreTestFunctionArn() + ":1"

	doc := resourcePolicyDoc(`{"Sid":"v1","Effect":"Allow","Principal":"*","Action":"lambda:InvokeFunction","Resource":"` + qualifiedArn + `"}`)
	put, err := svc.putResourcePolicyCore(store, &PutResourcePolicyInput{ResourceArn: qualifiedArn, Policy: doc})
	if err != nil {
		t.Fatalf("put on qualified arn: %v", err)
	}
	got, err := svc.getResourcePolicyCore(store, coreTestFunctionArn())
	if err != nil {
		t.Fatalf("get on unqualified arn: %v", err)
	}
	if got.RevisionId != put.RevisionId {
		t.Fatalf("qualified put and unqualified get revisions differ: %q vs %q", got.RevisionId, put.RevisionId)
	}
}
